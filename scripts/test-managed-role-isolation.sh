assert_linux_namespace_torn_down() {
  local output=$1 lock
  lock=$(find "$output/candidate-environment" -type f -name namespace-teardown.lock -print -quit)
  [[ -n $lock ]] || { echo 'Linux candidate teardown lock was not created' >&2; return 1; }
  # The lock is held by Bubblewrap until its PID namespace reaper has exited.
  # It is therefore the host-observable no-survivor proof even though fixture
  # PIDs inside the namespace are deliberately not host PIDs.
  flock -n "$lock" true || { echo 'Linux candidate namespace survivor still holds teardown lock' >&2; return 1; }
}

run_role_from() {
  local runner=$1 mode=$2 output=$3 identity=${4:-"$tmp/expected.json"}
  printf '%s\n' "$mode" >"$tmp/source/.fixture-mode"
  # FD 10 is deliberately non-CLOEXEC. The launcher must close it before the
  # fake Flutter process starts, while preserving Bash's own script reader.
  exec 10<"$tmp/parent-home/token"
  if HOME="$tmp/parent-home" XDG_CONFIG_HOME="$tmp/parent-config" GH_TOKEN=token-canary \
    GITHUB_TOKEN=token-canary ACTIONS_RUNTIME_TOKEN=artifact-canary \
    ACTIONS_ID_TOKEN_REQUEST_TOKEN=oidc-canary SSH_AUTH_SOCK="$tmp/agent.sock" \
    AWS_SECRET_ACCESS_KEY=cloud-canary ImageOS=fixture-linux ImageVersion=fixture-image RUNNER_TEMP="$tmp/runner-temp" PATH="$tmp/source/fixture-bin:$PATH" BURLMD_CARGO_EXPAND="$tmp/source/fixture-bin/cargo-expand" \
    EXPECTED_IDENTITY="$identity" \
    "$runner" linux-x86_64 "$tmp/source" "$output"; then
    status=0
  else
    status=$?
  fi
  # The child must close this non-CLOEXEC canary. Some Bash implementations
  # then reflect that closure in the caller's descriptor table, so cleanup is
  # intentionally idempotent after the actual no-leak assertion above.
  { exec 10<&-; } 2>/dev/null || true
  return "$status"
}

