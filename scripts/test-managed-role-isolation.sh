# This is the production nesting boundary, rather than a synthetic Bubblewrap
# probe: the actual trusted isolation assertion runs inside an already private
# candidate Bubblewrap namespace. Its inner sandbox receives only the exact
# locked Nix runtime closure supplied by the trusted launcher, never /nix or
# any broader host mount.
run_nested_production_isolation_fixture() {
  local tool resolved store_root bwrap_root path closure_value fixture_path missing_bwrap_value tampered_value
  local -a tools closure_paths path_entries outer_args
  tools=(bash sh env mkdir mktemp chmod awk rg bwrap cat sort readlink)
  for tool in "${tools[@]}"; do
    resolved=$(readlink -f "$(command -v "$tool")") || return 1
    [[ $resolved == /nix/store/* ]] || return 1
    store_root=$(printf '%s\n' "$resolved" | cut -d/ -f1-4)
    [[ $tool == bwrap ]] && bwrap_root=$store_root
    while IFS= read -r path; do closure_paths+=("$path"); done < <(nix-store -qR "$store_root")
    path_entries+=("$(dirname "$resolved")")
  done
  mapfile -t closure_paths < <(printf '%s\n' "${closure_paths[@]}" | LC_ALL=C sort -u)
  mapfile -t path_entries < <(printf '%s\n' "${path_entries[@]}" | LC_ALL=C sort -u)
  closure_value=$(IFS=:; printf '%s' "${closure_paths[*]}")
  fixture_path=$(IFS=:; printf '%s' "${path_entries[*]}")
  outer_args=(--unshare-all --die-with-parent --new-session --clearenv --setenv PATH "$fixture_path" --setenv BURLMD_LOCKED_NIX_CLOSURE "$closure_value" --proc /proc --dev /dev --tmpfs /tmp --dir /nix --dir /nix/store --dir /trusted --ro-bind "$root" /trusted --chdir /trusted)
  for path in "${closure_paths[@]}"; do outer_args+=(--ro-bind "$path" "$path"); done
  run_nested_assert() {
    local closure=$1 index
    local -a args=("${outer_args[@]}")
    for index in "${!args[@]}"; do
      [[ ${args[$index]} == BURLMD_LOCKED_NIX_CLOSURE ]] && args[$((index + 1))]=$closure
    done
    env -i PATH="$fixture_path" BURLMD_LOCKED_NIX_CLOSURE="$closure" \
      "$(command -v bwrap)" "${args[@]}" "$(command -v bash)" -ceu \
      'bash "$1" --contract "$2" --sandbox bubblewrap --expected-version 0.11.2' nested-isolation \
      /trusted/scripts/assert-managed-evidence-isolation.sh /trusted/.constitution/tech-spec/contracts/provisional-spikes.toml
  }
  run_nested_assert "$closure_value"

  # The nested verifier must fail closed when a trusted-launcher closure is
  # truncated or widened. These mutations happen outside the candidate mount,
  # so they exercise the actual injection boundary rather than a shell mock.
  missing_bwrap_value=$(printf '%s\n' "${closure_paths[@]}" | awk -v omitted="$bwrap_root" '$0 != omitted' | paste -sd:)
  if run_nested_assert "$missing_bwrap_value"; then
    echo 'nested isolation accepted an incomplete locked closure' >&2
    return 1
  fi
  tampered_value="$closure_value:/tmp"
  if run_nested_assert "$tampered_value"; then
    echo 'nested isolation accepted a non-store closure member' >&2
    return 1
  fi
}
run_nested_production_isolation_fixture

printf 'managed role candidate isolation fixture passed\n'
