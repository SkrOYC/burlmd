#!/usr/bin/env bash
# Adversarial coverage for the trusted candidate launcher. This uses a tiny
# candidate source and fake Flutter/Dart commands; it never needs a device or
# touches the caller's active desktop.
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd -P)
tmp=$(mktemp -d "${TMPDIR:-/tmp}/burlmd-managed-role.XXXXXXXX")
trap '[[ ${BURLMD_KEEP_FIXTURE_TMP:-} == 1 ]] || rm -rf -- "$tmp"' EXIT
mkdir -p "$tmp/source/integration_test" "$tmp/source/fixture" "$tmp/source/fixture-bin" "$tmp/parent-home" "$tmp/parent-config"
touch "$tmp/source/integration_test/fixture_test.dart"
printf '[package]\nname = "fixture"\nversion = "0.1.0"\nedition = "2024"\n' >"$tmp/source/fixture/Cargo.toml"
printf '# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "fixture"\nversion = "0.1.0"\n' >"$tmp/source/fixture/Cargo.lock"
git -C "$tmp/source" init -q
git -C "$tmp/source" config user.email fixture@example.invalid
git -C "$tmp/source" config user.name fixture
git -C "$tmp/source" add .
git -C "$tmp/source" commit -qm 'fixture tested source'
printf 'parent-token-canary\n' >"$tmp/parent-home/token"
printf 'parent-config-canary\n' >"$tmp/parent-config/config"

cat >"$tmp/source/fixture-bin/flutter" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
probe="$HOME/probe"; mkdir -p "$probe"
if [[ ${1:-} == --version ]]; then printf 'fixture flutter\n'; exit 0; fi
mode=$(<../.fixture-mode)

# Inspect the actual candidate exec child without depending on a host Perl
# binary. FD 255 is Bash's CLOEXEC script reader, not an inherited capability;
# FD 10+ must not reach this child.
if [[ -d /proc ]]; then
  nonstdio_fds=()
  for fd_path in /proc/$$/fd/[0-9]*; do
    fd=${fd_path##*/}
    ((fd > 2)) && nonstdio_fds+=("$fd")
  done
  printf '%s\n' "${nonstdio_fds[@]}" >"$probe/nonstdio-fds"
fi

for name in GH_TOKEN GITHUB_TOKEN ACTIONS_RUNTIME_TOKEN ACTIONS_RUNTIME_URL ACTIONS_RESULTS_URL ACTIONS_ID_TOKEN_REQUEST_TOKEN ACTIONS_ID_TOKEN_REQUEST_URL GITHUB_ACTIONS GITHUB_ENV GITHUB_OUTPUT GITHUB_PATH GITHUB_STEP_SUMMARY GIT_ASKPASS SSH_ASKPASS SSH_AUTH_SOCK AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY AZURE_CLIENT_SECRET GOOGLE_APPLICATION_CREDENTIALS; do
  [[ -z ${!name+x} ]] || { printf 'leaked:%s\n' "$name" >"$probe/leak"; exit 81; }
done
[[ $HOME == /candidate/home || $HOME == */candidate-environment/home ]] || { printf 'ambient-home\n' >"$probe/leak"; exit 82; }
candidate_root=$(dirname "$HOME")
[[ $XDG_CONFIG_HOME == "$candidate_root/xdg/config" && $GH_CONFIG_DIR == "$candidate_root/gh" && $CARGO_HOME == "$candidate_root/prepared/cargo-home" && $PUB_CACHE == "$candidate_root/prepared/pub-cache" && $CARGO_TARGET_DIR == "$candidate_root/writable/cargo-target" ]] || { printf 'owned-config-paths\n' >"$probe/leak"; exit 83; }
[[ ! -e "$HOME/token" && ! -e "$XDG_CONFIG_HOME/config" ]] || { printf 'ambient-config\n' >"$probe/leak"; exit 84; }
[[ -n ${BURLMD_CANDIDATE_SESSION:-} ]] || { printf 'missing-session\n' >"$probe/leak"; exit 85; }
case $mode in
  success)
    printf ready >"$probe/ready"
    exit 0
    ;;
  failure)
    sleep 30 & printf '%s\n' "$!" >"$probe/child.pid"
    printf ready >"$probe/ready"
    exit 41
    ;;
  detached)
    # Leave the candidate session and erase its environment. Linux Bubblewrap
    # must still reap this fresh-session descendant before returning.
    setsid env -i PATH="$PATH" HOME="$HOME" PROBE="$probe" bash -ceu 'printf "%s\n" "$$" > "$PROBE/detached.pid"; while :; do sleep 1; done' &
    for _ in $(seq 1 50); do
      if [[ -s $probe/detached.pid ]]; then
        printf ready >"$probe/ready"
        exit 0
      fi
      sleep 0.1
    done
    exit 86
    ;;
  interrupt)
    sleep 30 & printf '%s\n' "$!" >"$probe/child.pid"
    # The parent fixture only signals after this readiness marker, so it can
    # reliably assert that launcher interruption tears down the child too.
    printf ready >"$probe/ready"
    while :; do sleep 1; done
    ;;
  *) exit 87 ;;
esac
EOF
cat >"$tmp/source/fixture-bin/dart" <<'EOF'
