  local functions=$tmp/sway-exit-cleanup-functions.sh pid_file=$tmp/sway-exit-cleanup.pid status pid process_state
  # Extract the current runner bodies, so this checks its actual EXIT-path
  # cleanup rather than a copied approximation. The harness exits immediately
  # after registering a live compositor stand-in, matching an integration-gate
  # failure after private Sway has started.
  {
    sed -n '/^cleanup_private_store()/,/^}/p' "$root/scripts/run-managed-role.sh"
    sed -n '/^cleanup_role_exit()/,/^}/p' "$root/scripts/run-managed-role.sh"
    sed -n '/^stop_linux_private_sway_viewport()/,/^}/p' "$root/scripts/run-managed-role.sh"
  } >"$functions"
  set +e
  bash -ceu '
    source "$1"
    # This is the M003 cleanup branch.  The extracted functions do not include
    # the runner top-level ticket initialization, so provide the same
    # trusted invocation state the production M003 exit trap has.
    ticket=BURL-M003
    sleep 30 &
    LINUX_VIEWPORT_SWAY_PID=$!
    printf "%s\\n" "$LINUX_VIEWPORT_SWAY_PID" >"$2"
    trap '\''cleanup_role_exit "$?"'\'' EXIT
    exit 73
  ' sway-cleanup "$functions" "$pid_file"
  status=$?
  set -e
  [[ $status == 73 && -s $pid_file ]] || {
    echo 'Sway failure-path cleanup harness did not preserve the failing status' >&2
    return 1
  }
  pid=$(<"$pid_file")
  [[ $pid =~ ^[1-9][0-9]*$ ]] || return 1
  for _ in $(seq 1 20); do
    kill -0 "$pid" 2>/dev/null || return 0
    process_state=$(ps -o stat= -p "$pid" 2>/dev/null | tr -d ' ' || true)
    [[ $process_state == Z* ]] && return 0
    sleep 0.1
  done
  echo 'Sway process survived the runner EXIT-path cleanup' >&2
  return 1
}
assert_sway_failure_exit_cleanup

# This is the production candidate boundary, rather than a synthetic nested
# Bubblewrap probe. It uses the exact production namespace arguments; the
# assertion validates that already-established sandbox and never requests a
# second user-namespace UID map.
run_production_isolation_fixture() {
  local tool resolved store_root bwrap_executable missing_required_root path closure_value fixture_path missing_required_value tampered_value fake_bwrap nested_marker
  local -a tools closure_paths path_entries production_prefix outer_args
  # The M003 candidate receives only the active-isolation tool inventory.
  # Bubblewrap launches the outer namespace and must remain parent-only.
  tools=(bash sh env cat mkdir chmod awk rg sort readlink)
  for tool in "${tools[@]}"; do
    resolved=$(readlink -f "$(command -v "$tool")") || return 1
    [[ $resolved == /nix/store/* ]] || return 1
    store_root=$(printf '%s\n' "$resolved" | cut -d/ -f1-4)
    [[ $tool != bash ]] || missing_required_root=$store_root
    while IFS= read -r path; do closure_paths+=("$path"); done < <(nix-store -qR "$store_root")
    path_entries+=("$(dirname "$resolved")")
  done
  bwrap_executable=$(readlink -f "$(command -v bwrap)") || return 1
  [[ $bwrap_executable == /nix/store/* && -n ${missing_required_root:-} ]] || return 1
  mapfile -t closure_paths < <(printf '%s\n' "${closure_paths[@]}" | LC_ALL=C sort -u)
  mapfile -t path_entries < <(printf '%s\n' "${path_entries[@]}" | LC_ALL=C sort -u)
  closure_value=$(IFS=:; printf '%s' "${closure_paths[*]}")
  fixture_path=$(IFS=:; printf '%s' "${path_entries[*]}")
  # This is the production linux_candidate_bwrap namespace prefix. Keep the
  # user map and private-network options explicit: --unshare-all alone only
  # requests user namespaces on a best-effort basis in Bubblewrap 0.11.2.
  production_prefix=(--unshare-all --unshare-user --uid 0 --gid 0 --unshare-net --cap-add CAP_NET_ADMIN --die-with-parent --new-session --clearenv)
  outer_args=("${production_prefix[@]}" --setenv PATH "$fixture_path" --setenv BURLMD_LOCKED_NIX_CLOSURE "$closure_value" --proc /proc --dev /dev --tmpfs /tmp --dir /nix --dir /nix/store --dir /trusted --ro-bind "$root" /trusted --chdir /trusted)
  for path in "${closure_paths[@]}"; do outer_args+=(--ro-bind "$path" "$path"); done
  run_candidate_assert() {
    local closure=$1 index
    shift
    local -a args=("${outer_args[@]}")
    for index in "${!args[@]}"; do
      [[ ${args[$index]} == BURLMD_LOCKED_NIX_CLOSURE ]] && args[$((index + 1))]=$closure
    done
    args+=("$@")
    env -i PATH="$fixture_path" GH_TOKEN=fixture-canary AWS_SECRET_ACCESS_KEY=fixture-canary BURLMD_LOCKED_NIX_CLOSURE="$closure" \
      "$bwrap_executable" "${args[@]}" "$(command -v bash)" -ceu \
      'bash "$1" --contract "$2" --sandbox bubblewrap --expected-version 0.11.2' candidate-isolation \
      /trusted/scripts/assert-managed-evidence-isolation.sh /trusted/.constitution/tech-spec/contracts/provisional-spikes.toml
  }
  run_candidate_assert "$closure_value"

  # The active-boundary verifier must fail closed when a trusted-launcher closure is
  # truncated or widened. These mutations happen outside the candidate mount,
  # so they exercise the actual injection boundary rather than a shell mock.
  missing_required_value=$(printf '%s\n' "${closure_paths[@]}" | awk -v omitted="$missing_required_root" '$0 != omitted' | paste -sd:)
  if run_candidate_assert "$missing_required_value"; then
    echo 'production-shaped isolation accepted an incomplete locked closure' >&2
    return 1
  fi
  tampered_value="$closure_value:/tmp"
  if run_candidate_assert "$tampered_value"; then
    echo 'production-shaped isolation accepted a non-store closure member' >&2
    return 1
  fi
  if run_candidate_assert "$closure_value" --setenv GH_TOKEN credential-canary; then
    echo 'production-shaped isolation accepted a credential capability' >&2
    return 1
  fi
  if run_candidate_assert "$closure_value" --share-net; then
    echo 'production-shaped isolation accepted the host network namespace' >&2
    return 1
  fi
  if run_candidate_assert "$closure_value" --uid 42 --gid 42; then
    echo 'production-shaped isolation accepted a broadened user map' >&2
    return 1
  fi

  # Bubblewrap is parent-only in M003. A visible executable must reject before
  # it can be invoked as a nested namespace launcher.
  fake_bwrap=$tmp/no-nested-bwrap
  nested_marker=$tmp/nested-bwrap-invocation
  printf '#!%s\nif [[ ${1:-} == --version ]]; then printf "bubblewrap 0.11.2\\n"; exit 0; fi\nprintf nested-bwrap >"$BURLMD_NESTED_BWRAP_MARKER"\nexit 97\n' \
    "$(command -v bash)" >"$fake_bwrap"
  chmod 0555 "$fake_bwrap"
  if run_candidate_assert "$closure_value" \
    --dir /fixture --bind "$tmp" /fixture --setenv BURLMD_NESTED_BWRAP_MARKER /fixture/nested-bwrap-invocation \
    --ro-bind "$fake_bwrap" "$bwrap_executable"; then
    echo 'production-shaped isolation accepted visible parent-only Bubblewrap' >&2
    return 1
  fi
  [[ ! -e $nested_marker ]] || {
    echo 'candidate isolation started a nested Bubblewrap namespace' >&2
    return 1
  }
}
run_production_isolation_fixture

